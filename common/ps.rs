// Строки для PowerShell — одна семантика на все подсистемы.
//
// До 07.09 под именем `ps_quote` жили ДВА контракта: оболочка возвращала
// строку В одинарных кавычках («'…'» с удвоенным апострофом), установщик —
// только удвоенный апостроф без кавычек (ревью 06.09, §4 п. 4). Одно имя,
// два ответа — это мина для того, кто переносит вызов из одного файла в
// другой. Теперь имена разные и оба здесь: `ps_escape` — внутренность
// одинарных кавычек, `ps_quote` — готовый литерал.
//
// Без удвоения путь вида `C:\Users\O'Brien\…` рвёт скрипт целиком
// (ParserError), а отказ глотался — гашение процессов и ярлыки молча не
// работали.

/// Текст ВНУТРИ одинарных кавычек PowerShell: апостроф удваивается, больше в
/// одинарных кавычках ничего не значимо (ни `$`, ни обратный апостроф).
fn ps_escape(s: &str) -> String {
    s.replace('\'', "''")
}

/// Готовый строковый литерал: `'…'` с экранированной внутренностью.
fn ps_quote(s: &str) -> String {
    format!("'{}'", ps_escape(s))
}

#[cfg(test)]
mod ps_tests {
    use super::*;

    #[test]
    fn escape_doubles_apostrophe_only() {
        assert_eq!(ps_escape(r"C:\Users\O'Brien"), r"C:\Users\O''Brien");
        assert_eq!(ps_escape("$env:TEMP `x`"), "$env:TEMP `x`");
    }

    #[test]
    fn quote_wraps_escaped_text() {
        assert_eq!(ps_quote("это 'моё'"), "'это ''моё'''");
        assert_eq!(ps_quote(""), "''");
    }
}
