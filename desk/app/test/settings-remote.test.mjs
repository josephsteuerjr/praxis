// Тест против одного класса: окно ругается на чужой харнесс.
//
// Praxis — это то же окно, но агент живёт НА СЕРВЕРЕ. Настройки же читались из
// локального файла Praxis и рисовались всегда — и владелец 09.09 увидел на
// одном экране: пустые поля модели и Telegram (их неоткуда взять), «модуль
// режима не нашёлся рядом с каналом», «Про управление компьютером харнесс ничего
// не рассказал», «Снимок устройства пуст — просьб не видно», путь к пустой папке
// данных и «Канал не пустил: только с этой машины (403)» на кнопке QR. Ни одно
// из этого не было поломкой: окно спрашивало у чужого харнесса то, чего у него и
// не должно быть.
//
// ⚠ ЧТО ИЗМЕНИЛОСЬ 10.09. Правило держалось сорока четырьмя ветками
// `if (remote)` в общем экране, и стенд стерёг каждую из них поимённо. Теперь
// правило — не ветка, а СТРУКТУРА: карточек местного агента в сборке Praxis нет
// вовсе. Поэтому стенд стережёт границу, а не условия:
//
//   1. общий каркас не знает ни про `remote`, ни про карточки местного агента;
//   2. карточки местного агента живут у Элен и только у неё;
//   3. Praxis их не импортирует ни прямо, ни через окно;
//   4. то, что у изданий разное (подпись имён, адрес телефона), каркас СПРАШИВАЕТ
//      у издания, а не решает сам.
//
// Ветка `if (remote)`, вернувшаяся в общий файл, — это возвращение заплатки:
// стенд обязан покраснеть на ней раньше, чем она доедет до владельца.
//
// Запуск: node app/test/settings-remote.test.mjs (из корня desk/ или из app/).

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { strict as assert } from "node:assert";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "..", "src");
const desk = join(here, "..", "..");
const win = join(desk, "ui-kit", "window");
const remote = join(desk, "remote", "src");

/** Комментарии — не код: в них те же слова разбираются словами. */
const code = (text) => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");
const read = (...p) => code(readFileSync(join(...p), "utf8"));

const frame = read(win, "views", "settings-frame.ts");
const chrome = read(win, "main.ts");
const agent = read(app, "settings-agent.ts");
const server = read(remote, "settings-server.ts");
const remoteMain = read(remote, "main.ts");
const heleneMain = read(app, "main.ts");

// --------------------------------------------------------------------------
// 1. Общий каркас не знает про удалённый харнесс.
// --------------------------------------------------------------------------

// Стережём ВЕТВЛЕНИЕ, а не слово. Само значение `mode: local | remote` — общий
// ключ конфига: где живёт харнесс. Его пишет карточка «Перенос», и она есть у
// обоих изданий (Элен может уйти на сервер, окну к серверу без адреса не с кем
// связываться). Заплатка выглядела иначе — `if (remote) …` решала, какие
// карточки рисовать, и вот это вернуться не должно.
const BRANCH = /(if\s*\(\s*!?\s*remote\s*\)|\bremote\s*\?|\?\s*remote\b|&&\s*!?remote\b)/;
// Смотрим на СОСТАВ экрана, а не на весь файл. Внутри карточки телефона ветка
// по `remoteBase` законна и остаётся: она решает, куда ведёт QR — на сервер или
// на эту машину, — а это разница КОНФИГА, а не изданий. Элен тоже может уйти на
// сервер карточкой «Перенос», и тогда её телефон обязан вести туда же.
const compose = frame.slice(frame.indexOf("async function render("),
                            frame.indexOf("function mountSettings("));
for (const [name, text] of [["settings-frame.ts", compose], ["main.ts окна", chrome]]) {
  assert.ok(
    !BRANCH.test(text.replace(/remoteBase|remoteOn|remoteKey|needs_remote/g, "_")),
    `в общем ${name} вернулась ветка про удалённый харнесс: состав экрана снова ` +
      "выводится условием, а не приносится изданием. Разрез прошёл не там.",
  );
}
assert.ok(compose.length > 500, "состав экрана не нашёлся — стенд устарел, а не код");

// Карточек местного агента в каркасе нет ни одной — ни рисующих, ни пишущих.
for (const local of ["mountsCard", "computerCard", "modeCard", "relayBaseUrl", "ANTHROPIC_PRESETS"]) {
  assert.ok(!frame.includes(local), `каркас снова знает про карточку местного агента: ${local}`);
}

// --------------------------------------------------------------------------
// 2. Карточки местного агента — у Элен, и их сбор в конфиг тоже.
// --------------------------------------------------------------------------

for (const card of ['card("Модель"', 'card("Telegram"', "mode.el", 'card("Песочница"',
                    "mounts.el", "computer.el", 'card("Данные агента"']) {
  assert.ok(agent.includes(card), `карточка пропала из издания Элен: ${card}`);
}
for (const write of ["out.model", "out.telegram", "out[MODE_KEY]", "out.sandbox", "out.computer"]) {
  assert.ok(agent.includes(write), `издание Элен перестало писать в конфиг: ${write}`);
}

// --------------------------------------------------------------------------
// 3. Praxis не тянет к себе ни карточек агента, ни самого издания Элен.
// --------------------------------------------------------------------------

for (const forbidden of ["settings-agent", "modecard", "mounts", "computer", "relay"]) {
  assert.ok(
    !new RegExp(`from "[^"]*${forbidden}"`).test(server + remoteMain),
    `Praxis импортирует часть Элен: ${forbidden}. Агента рядом с ним нет, ` +
      "и настраивать эти карточки нечего.",
  );
}
assert.match(remoteMain, /start\(\{ settingsEdition: serverEdition/,
  "Praxis поднимает окно не своим изданием настроек");
assert.match(heleneMain, /start\(\{ settingsEdition: agentEdition/,
  "Элен поднимает окно не своим изданием настроек");

// Имя продукта ставит издание: «Hélène», вшитая в общий слой, подписывала бы
// Praxis чужим именем — в заголовке окна, на полке и в служебных плашках чата.
assert.match(heleneMain, /productName: "Hélène"/, "Элен перестала называть себя по имени");
assert.match(remoteMain, /productName: "Praxis"/, "Praxis снова подписан чужим именем");
assert.match(chrome, /setProductName\(opts\.productName\);/,
  "общий слой перестал брать имя продукта у издания — значит взял своё");

// --------------------------------------------------------------------------
// 4. Разное у изданий каркас СПРАШИВАЕТ, а не решает.
// --------------------------------------------------------------------------

assert.match(frame, /card\("Имена", names, built\.namesHint\)/,
  "подпись под именами снова выбирается в каркасе, а у изданий она разная");
assert.match(frame, /phoneCard\(draft, !!c\.phone\?\.enabled, built\.phoneBase, built\.qrSvg\)/,
  "адрес для телефона снова решает каркас, а не издание");
assert.match(frame, /const modeNote = built\.note\(\);/,
  "хвост расписки снова берётся из карточки режима, которой у издания к серверу нет");

// Телефон Praxis ведёт на СЕРВЕР, а телефон Элен — на эту машину.
assert.match(server, /phoneBase: base,/, "QR Praxis больше не ведёт на адрес сервера");
assert.match(agent, /phoneBase: "",/, "телефон Элен больше не подключается к этой машине");

// --------------------------------------------------------------------------
// 5. Первый запуск — у издания к серверу, и только у него.
// --------------------------------------------------------------------------

assert.ok(!chrome.includes("askForServer"),
  "карточка подключения к серверу вернулась в общее окно: у Элен харнесс рядом");
assert.match(read(remote, "first-run.ts"), /if \(!cfg\.needs_remote\) return false;/,
  "Praxis снова показывает карточку подключения там, где адрес уже вписан");

// 6. Пустой адрес обновлений не делает кнопку мёртвой (живой Praxis, 09.09).
assert.match(frame, /url: String\(draft\.update\?\.url \|\| ""\)\.trim\(\) \|\| UPDATE_URL_DEFAULT,/,
  "проверка обновлений снова уходит с пустым адресом");

console.log("разделение окна: издания не залезают друг к другу");
