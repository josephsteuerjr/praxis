/**
 * Схема хода: слева — что приезжает модели, справа — что она делает.
 *
 * ⚠ Ни строки про кэш: «K, E и A отдаются из кэша, платишь только за T» — по
 * замерам 16.09 неправда (зрячая модель не кэширует никогда, 86 % свежего счёта
 * — холодные старты). Выдумка, выгравированная в самой долгоживущей форме
 * интерфейса, переживает тех, кто её написал.
 *
 * Кегли ≥ 12px и ничего бледнее `--ink-2`: `--muted` на белом даёт 2,75:1 при
 * норме 4,5 — на схеме это был бы текст, который видно не всем.
 */
function diagram(): string {
  const box = (x: number, y: number, w: number, h: number, title: string, sub: string, accent = false) => `
    <rect x="${x}" y="${y}" width="${w}" height="${h}" rx="10"
          fill="var(--surface)" stroke="${accent ? "var(--accent)" : "var(--line)"}"/>
    <text x="${x + 14}" y="${y + 24}" font-size="13" fill="var(--ink)">${esc(title)}</text>
    ${sub ? `<text x="${x + 14}" y="${y + 42}" font-size="12" fill="var(--ink-2)">${esc(sub)}</text>` : ""}`;
  const arrow = (x1: number, y1: number, x2: number, y2: number) => `
    <path d="M${x1} ${y1} L${x2} ${y2}" stroke="var(--ink-3)" stroke-width="1.5" marker-end="url(#a-head)"/>`;

  return `<div class="dia-wrap"><svg class="dia" viewBox="0 0 700 340" role="img"
       aria-label="Схема одного хода: слово превращается в кадр, модель думает, зовёт тулы и отвечает тулом reply">
    <defs>
      <marker id="a-head" viewBox="0 0 8 8" refX="7" refY="4" markerWidth="7" markerHeight="7" orient="auto">
        <path d="M0 0 L8 4 L0 8 z" fill="var(--ink-3)"/>
      </marker>
    </defs>
    <text x="14" y="18" font-size="12" fill="var(--ink-2)">ЧТО ПРИЕЗЖАЕТ МОДЕЛИ</text>
    ${box(14, 30, 260, 56, "Твоё слово", "сначала ложится в память")}
    ${arrow(144, 90, 144, 112)}
    ${box(14, 116, 260, 56, "Память", "досье, дневник, архив комнаты")}
    ${arrow(144, 176, 144, 198)}
    ${box(14, 202, 260, 122, "Кадр — K · E · A · T", "")}
    <text x="28" y="248" font-size="12" fill="var(--ink-2)">K — конституция: кто он и чего не делает</text>
    <text x="28" y="268" font-size="12" fill="var(--ink-2)">E — эпоха: слепок знаний о себе</text>
    <text x="28" y="288" font-size="12" fill="var(--ink-2)">A — накопитель: разговор целиком</text>
    <text x="28" y="308" font-size="12" fill="var(--ink-2)">T — текущее: кто говорит и что сейчас</text>

    <path d="M274 258 L322 258 L322 74 L356 74" stroke="var(--ink-3)" stroke-width="1.5" fill="none" marker-end="url(#a-head)"/>

    <text x="360" y="18" font-size="12" fill="var(--ink-2)">ЧТО ДЕЛАЕТ АГЕНТ</text>
    ${box(360, 48, 300, 52, "Думает", "решает, чего не хватает")}
    ${arrow(510, 104, 510, 126)}
    ${box(360, 130, 300, 52, "Зовёт тул", "поиск, файл, память, компьютер")}
    <path d="M660 156 C690 156 690 74 668 74 L664 74" stroke="var(--accent)" stroke-width="1.5"
          fill="none" stroke-dasharray="4 4" marker-end="url(#a-head)"/>
    <text x="596" y="116" font-size="12" fill="var(--accent)">и снова, пока нужно</text>
    ${arrow(510, 186, 510, 208)}
    ${box(360, 212, 300, 52, "Отвечает тулом reply", "именно она уносит слова наружу", true)}
    ${arrow(510, 268, 510, 290)}
    ${box(360, 294, 300, 40, "Закрывает ход сам", "молчание — тоже его решение")}
  </svg></div>`;
}

