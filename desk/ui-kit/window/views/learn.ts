export async function render(container: HTMLElement): Promise<void> {
  const local = LOCAL_AGENT;
  const tasks = TASKS.filter((t) => local || !t.local);
  container.innerHTML = `<div class="center learn">
    <p class="learn-lead">Агент работает тулами: ищет, читает, пишет, помнит, просыпается по расписанию.
      Ниже — рамки задач с пропусками: нажми, и она уедет в поле ввода, а пропуски заполнишь ты.</p>
    <h3 class="section-title">Как идёт один ход</h3>
    ${diagram()}
    <h3 class="section-title">Что можно поручить <span class="muted">${tasks.length}</span></h3>
    <div class="learn-grid">
      ${tasks
        .map(
          (t, i) => `<button class="learn-card" type="button" data-task="${i}">
            <b>${esc(t.title)}</b>
            <span class="learn-what">${esc(t.what)}</span>
            <span class="learn-tpl">${esc(t.template)}</span>
          </button>`,
        )
        .join("")}
    </div>
    <h3 class="section-title">Как с ним разговаривать</h3>
    <div class="learn-how">
      ${HOW.map(([h, p]) => `<div class="card"><b>${esc(h)}</b><p>${esc(p)}</p></div>`).join("")}
    </div>
  </div>`;

  for (const b of container.querySelectorAll<HTMLButtonElement>("[data-task]")) {
    b.addEventListener("click", () => {
      const t = tasks[Number(b.dataset.task)];
      if (!t) return;
      // Раздел не пишет в поле сам: он просит каркас открыть переписку с
      // агентом ЭТОГО окна и положить туда рамку. Каркас знает и про черновик,
      // который нельзя затирать, и про то, в какую комнату это класть.
      dispatchEvent(new CustomEvent("frame-template", { detail: t.template }));
    });
  }
}
