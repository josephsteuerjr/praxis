let seq = 0;
export const nextId = () => `m${++seq}`;

/** Начальная лента: вчера и сегодня, по очереди «он — она». */
export function seed(count = 24, now = Date.now()): Msg[] {
  const out: Msg[] = [];
  const start = now - 26 * 3600_000;
  const step = (26 * 3600_000 - 20 * 60_000) / count;
  out.push({ id: nextId(), who: "system", at: start - 60_000, text: "Мира проснулась — ночной цикл памяти закончен, 214 записей свёрнуто в сводку." });
  for (let i = 0; i < count; i++) {
    const k = Math.floor(i / 2) % OWNER.length;
    const at = start + i * step;
    if (i % 2 === 0) out.push({ id: nextId(), who: "owner", at, text: OWNER[k] });
    else out.push({ id: nextId(), who: "agent", at, text: AGENT[k] });
  }
  return out;
}

export function ownerLine(i: number): string {
  return OWNER[i % OWNER.length];
}

export function agentLine(i: number): string {
  return AGENT[i % AGENT.length];
}

