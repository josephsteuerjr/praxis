//! Масштаб экрана: сказать системе, что мы считаем в настоящих пикселях.
//!
//! Windows врёт неосведомлённым о масштабе процессам — и врёт правдоподобно.
//! Процесс, не объявивший осведомлённости, получает от `GetWindowRect`, метрик экрана
//! и `SendInput` координаты в вымысле «96 точек на дюйм», а UI Automation отвечает
//! настоящими пикселями. Пока монитор один и масштаб 100 %, вымысел совпадает с
//! правдой. На 150 % — уже нет: прочитали прямоугольник кнопки (правда), ударили в его
//! середину (вымысел) и промахнулись. Выглядит это как «иногда не срабатывает».
//!
//! Поэтому тело объявляет себя осведомлённым НА КАЖДЫЙ МОНИТОР (v2) первой же строкой
//! `main`, до любого обращения к окнам. Дальше все три источника чисел говорят об
//! одном и том же пикселе.
//!
//! ⚠ Объявить это можно только ОДИН раз и только до первого обращения к окнам —
//! дальше система отвечает отказом. Поэтому здесь нет ни настройки, ни ручки: это
//! свойство программы, а не выбор владельца.

/// Что вышло. Строкой — её видно в журнале тела и в паспорте.
pub fn announce() -> &'static str {
    inner()
}

#[cfg(windows)]
fn inner() -> &'static str {
    use windows::Win32::UI::HiDpi::{
        DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2, SetProcessDpiAwarenessContext,
    };
    let done = unsafe { SetProcessDpiAwarenessContext(DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2) };
    match done {
        Ok(()) => {
            tracing::info!("dpi: per-monitor v2 — координаты считаем в настоящих пикселях");
            "per-monitor-v2"
        }
        Err(error) => {
            // Отказ здесь — не поломка: так отвечает система, когда осведомлённость уже
            // объявлена (манифестом или родителем). Молчать о нём всё равно нельзя:
            // если объявлено ЧУЖОЕ значение, числа снова разойдутся, и знать об этом
            // надо до первого промаха, а не после.
            tracing::warn!(
                "dpi: осведомлённость не объявлена ({error}) — либо она уже задана \
                 (манифестом или родительским процессом), либо система старая; \
                 прямоугольники окон и координаты клика могут расходиться на масштабе"
            );
            "already-set-or-unsupported"
        }
    }
}

#[cfg(not(windows))]
fn inner() -> &'static str {
    "not-windows"
}
