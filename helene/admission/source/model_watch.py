"""Терминальная остановка хода на вызовах модели (05.10, слово владельца).

Вызовы модели внутри хода — голос, судья приватности, разведчик — не имеют
кооперативной границы: SDK может ждать сети до собственного таймаута (по
умолчанию — десятки минут), и все гейты хода (`agent._run_status_gate`) до
возврата вызова не добираются. Отсюда жалоба владельца: «когда не отправляется
из-за проблем с сетью, тоже нельзя остановить».

Здесь вызов уходит в дочерний поток, а поток хода ждёт его короткими порциями и
между ними спрашивает состояние прогона. Всё, что не «running» — отменено,
приостановлено или повисло в сомнении, — поднимает стоп-исключение НЕМЕДЛЕННО:
остановка хода терминальна, точка. Фоновые между ходами вызовы (свёртка,
резюме) — не ход, они ждут как раньше.

Брошенный дочерний поток доделывает свой HTTP вхолостую: ответ выбрасывается,
никто его не доставляет. Дублирования реплики это не создаёт — доставка всегда
начинается только ПОСЛЕ возврата из вызова, а не внутри него. Побочные записи
(расход, след вызова) остаются честными: поход в сеть был. А вот СБОЙ брошенного
вызова больше не трогает здоровье канала: `on_abandon`/`on_settle` дают
владельцу вызова (llm) пометить нить призраком — удержания эндпойнтов и
«мозг» принадлежат живым ходам, не мёртвым.

Контекст снапшотится ДО старта нити: трейс вызова не теряет ни итерацию
тул-цикла, ни привязку прогона, ни кадр — свежая нить в питоне начинает с
пустого контекста, и без копии атрибуция `"iter"`/`run`/`chat` в llm_calls.jsonl
молча обнулялась бы (поймано адверсарным ревью 05.10, живая проба).
"""
from __future__ import annotations

import contextvars
import logging
import threading

log = logging.getLogger(__name__)

#: Как часто поток хода перечитывает манифест прогона, пока модель в сети.
POLL_SEC = 0.5


def call_with_stop(work, on_stop, poll_sec: float = POLL_SEC,
                   on_abandon=None, on_settle=None):
    """Выполнить work() в дочернем потоке, пока on_stop не вернёт исключение.

    work      — вызов без аргументов (обычно замыкание над llm.chat с готовым
                контекстом); его результат или исключение возвращаются как есть.
    on_stop   — спрашивается каждые poll_sec секунд; None — ход жив, ждём дальше;
                исключение — поднимается в вызывающем потоке немедленно.
    on_abandon(ident) — нить БРОШЕНА (стоп выиграл): её поздний сбой не должен
                отравлять состояние канала; ident — threading ident нити.
    on_settle(ident)  — брошенная нить доделалась (снять пометку, ident мог бы
                быть переиспользован новой нитью).
    poll_sec  — период опроса; <= 0 — ждать без опроса (для стендов).

    Дочерний поток демонический: брошенный вызов не держит процесс.
    """
    done = threading.Event()
    box: dict = {}
    ctx = contextvars.copy_context()

    def _inner() -> None:
        try:
            box["value"] = work()
        except BaseException as exc:  # noqa: BLE001 — пересылаем в поток хода как есть
            box["error"] = exc
        finally:
            done.set()
            if on_settle is not None:
                try:
                    on_settle(threading.get_ident())
                except Exception:
                    log.exception("on_settle не отработал — пометка призрака может протухнуть")

    worker = threading.Thread(target=lambda: ctx.run(_inner), name="model-call",
                              daemon=True)
    worker.start()
    if poll_sec <= 0:
        done.wait()
    while not done.wait(poll_sec):
        stop = on_stop()
        if stop is not None:
            if on_abandon is not None:
                try:
                    on_abandon(worker.ident)
                except Exception:
                    log.exception("on_abandon не отработал — призрак сможет отравить канал")
            log.warning("вызов модели брошен: ход остановлен владельцем, сеть больше не ждётся")
            raise stop
    if "error" in box:
        raise box["error"]
    return box["value"]
