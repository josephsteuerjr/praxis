// прогоном: app/test/config-blocks.test.mjs.
//
// ⚠⚠ ЗДЕСЬ ЛЕЧИТСЯ ЦЕЛЫЙ КЛАСС, А НЕ ОДИН СЛУЧАЙ. Экран настроек знает не весь
// файл: часть ключей кладёт туда установщик, часть — харнесс, часть владелец
// руками. Пересборка блока (`out.X = { … }`) выбрасывает всё, чего экран не
// знает, молча и без отмены. Так уже дважды терялись живые данные:
//
//   1. `relay.instructions` — ручка, которой оболочка гасит 23 КБ чужого
//      системного промпта Codex CLI перед конституцией. Исчезала при первом же
//      «Сохранить», и агент получал обратно чужой промпт.
//   2. `sandbox.mounts` и `sandbox.mounts_denied` — весь список смонтированных
//      папок и записанные отказы владельца. Вся работа по монтированию
//      обнулялась одним кликом.
//
// Поэтому объектные блоки экран пишет только через `keepBlock`.

/**
 * Слить блок конфига с тем, что кладёт в него экран.
 *
 * Не объект на входе (блока нет, лежит строка или массив) — считаем пустым:
 * сливать не с чем, но и падать не с чего. Массив здесь именно «пусто», а не
 * «объект»: спред массива дал бы блок с ключами `"0"`, `"1"`, и харнесс прочёл
 * бы мусор вместо блока.
 */
export function keepBlock<T extends Record<string, unknown>>(base: unknown, patch: T): T & Record<string, unknown> {
  const was = base && typeof base === "object" && !Array.isArray(base) ? (base as Record<string, unknown>) : {};
  return { ...was, ...patch };
}
